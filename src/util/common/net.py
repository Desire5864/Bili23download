"""
监听地址的解析。

「默认只绑环回地址」是本项目的安全基线：MCP 服务器与 Web 面板都据此决定监听
地址。抽成公共函数是因为两者必须给出同一个答案 —— 各写一份迟早会分叉，
而这类分叉的方向往往是"某一处悄悄放宽成了 0.0.0.0"。
"""

import os

# 默认只绑环回地址：本机的浏览器与其它进程可达，局域网内的其它设备不可达。
# 这是安全默认值，不要改
DEFAULT_BIND_HOST = "127.0.0.1"

# 覆盖监听地址的环境变量。只有容器这类"进程本身即网络边界"的场景才需要它：
# 容器内的 127.0.0.1 是容器自己的环回地址，从宿主机与其它容器都连不上，
# 因此端口映射形同虚设，必须绑到 0.0.0.0 再由运维决定暴露给谁。
# 采用环境变量而非配置项，是因为它属于部署形态而非用户偏好，
# 且必须在配置界面能被打开之前就生效（首启时这些服务恰恰是关着的）
MCP_BIND_HOST_ENV = "BILI23_MCP_HOST"
WEB_BIND_HOST_ENV = "BILI23_WEB_HOST"

def resolve_bind_host(env_name: str) -> str:
    """
    解析监听地址：环境变量 > 默认的环回地址

    留空或只剩空白一律按未设置处理，避免 `BILI23_MCP_HOST=` 这种写法
    被当成"绑定到空主机名"而落到 0.0.0.0 上
    """
    host = os.environ.get(env_name, "").strip()

    return host or DEFAULT_BIND_HOST
